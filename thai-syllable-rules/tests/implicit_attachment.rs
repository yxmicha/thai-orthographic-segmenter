#![allow(
    clippy::too_many_lines,
    reason = "fixture tests list their expected segmentations inline"
)]
mod text_part;

use text_part::{TextPart, text_parts};
use thai_syllable_rules::split;

#[test]
fn keeps_two_consonant_attachment_candidates_separate() {
    let cases = [
        (
            "บากลม",
            vec![
                TextPart::Syllable("บา"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ลม"),
            ],
        ),
        (
            "การกรอง",
            vec![
                TextPart::Syllable("กา"),
                TextPart::Undecided("ร"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("รอง"),
            ],
        ),
        (
            "การกลับ",
            vec![
                TextPart::Syllable("กา"),
                TextPart::Undecided("ร"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ลับ"),
            ],
        ),
        (
            "การกลาย",
            vec![
                TextPart::Syllable("กา"),
                TextPart::Undecided("ร"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ลาย"),
            ],
        ),
        (
            "การกราบ",
            vec![
                TextPart::Syllable("กา"),
                TextPart::Undecided("ร"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ราบ"),
            ],
        ),
        (
            "การกรอก",
            vec![
                TextPart::Syllable("กา"),
                TextPart::Undecided("ร"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("รอก"),
            ],
        ),
        (
            "การกร่อน",
            vec![
                TextPart::Syllable("กา"),
                TextPart::Undecided("ร"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ร่อน"),
            ],
        ),
        (
            "การกวาด",
            vec![
                TextPart::Syllable("กา"),
                TextPart::Undecided("ร"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("วาด"),
            ],
        ),
        (
            "การกลั่น",
            vec![
                TextPart::Syllable("กา"),
                TextPart::Undecided("ร"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ลั่น"),
            ],
        ),
        (
            "อาจกลับ",
            vec![
                TextPart::Syllable("อา"),
                TextPart::Undecided("จ"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ลับ"),
            ],
        ),
        (
            "อาจกลาย",
            vec![
                TextPart::Syllable("อา"),
                TextPart::Undecided("จ"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ลาย"),
            ],
        ),
        (
            "อาจกรอง",
            vec![
                TextPart::Syllable("อา"),
                TextPart::Undecided("จ"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("รอง"),
            ],
        ),
        (
            "รูปกลม",
            vec![
                TextPart::Syllable("รู"),
                TextPart::Undecided("ป"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ลม"),
            ],
        ),
        (
            "รูปกรวย",
            vec![
                TextPart::Syllable("รู"),
                TextPart::Undecided("ป"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("รวย"),
            ],
        ),
        (
            "รูปกวาง",
            vec![
                TextPart::Syllable("รู"),
                TextPart::Undecided("ป"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("วาง"),
            ],
        ),
        (
            "พานกลม",
            vec![
                TextPart::Syllable("พา"),
                TextPart::Undecided("น"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ลม"),
            ],
        ),
        (
            "งานกลุ่ม",
            vec![
                TextPart::Syllable("งา"),
                TextPart::Undecided("น"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ลุ่ม"),
            ],
        ),
        (
            "คางกลม",
            vec![
                TextPart::Syllable("คา"),
                TextPart::Undecided("ง"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ลม"),
            ],
        ),
        (
            "วางกรวย",
            vec![
                TextPart::Syllable("วา"),
                TextPart::Undecided("ง"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("รวย"),
            ],
        ),
        (
            "วางกลอง",
            vec![
                TextPart::Syllable("วา"),
                TextPart::Undecided("ง"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ลอง"),
            ],
        ),
        (
            "วางกล่อง",
            vec![
                TextPart::Syllable("วา"),
                TextPart::Undecided("ง"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("ล่อง"),
            ],
        ),
        (
            "ทอดกรอบ",
            vec![
                TextPart::Syllable("ทอ"),
                TextPart::Undecided("ด"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("รอบ"),
            ],
        ),
        (
            "วาดกรอบ",
            vec![
                TextPart::Syllable("วา"),
                TextPart::Undecided("ด"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("รอบ"),
            ],
        ),
        (
            "วาดกวาง",
            vec![
                TextPart::Syllable("วา"),
                TextPart::Undecided("ด"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("วาง"),
            ],
        ),
        (
            "ขาดกรอบ",
            vec![
                TextPart::Syllable("ขา"),
                TextPart::Undecided("ด"),
                TextPart::Undecided("ก"),
                TextPart::Syllable("รอบ"),
            ],
        ),
        (
            "สกดสกปรก",
            vec![
                TextPart::Syllable("สกด"),
                TextPart::Undecided("ส"),
                TextPart::Undecided("ก"),
                TextPart::Undecided("ป"),
                TextPart::Syllable("รก"),
            ],
        ),
        (
            "กดสกปรก",
            vec![
                TextPart::Syllable("กด"),
                TextPart::Undecided("ส"),
                TextPart::Undecided("ก"),
                TextPart::Undecided("ป"),
                TextPart::Syllable("รก"),
            ],
        ),
    ];

    for (source, expected) in cases {
        assert_eq!(text_parts(source, &split(source)), expected, "{source}");
    }
}
